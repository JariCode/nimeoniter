import { Buffer } from 'node:buffer'
import process from 'node:process'
import react from '@vitejs/plugin-react'
import { defineConfig, loadEnv } from 'vite'

// Clerk's Frontend API host is encoded in the publishable key:
// pk_test_/pk_live_ + base64("<host>$"). Deriving it here keeps the CSP in
// sync with whichever Clerk instance the .env points at (dev or production).
function clerkFrontendApi(publishableKey) {
  if (!publishableKey) return null
  const encoded = publishableKey.split('_').slice(2).join('_')
  const host = Buffer.from(encoded, 'base64').toString('utf8').replace(/\$$/, '')
  return host ? `https://${host}` : null
}

// Security headers for the built app. Used by `vite preview` (local ZAP
// scans) and written to dist/.htaccess for the Apache production host, so
// both serve exactly the same policy. The dev server is left without them:
// Vite's HMR relies on inline scripts that this CSP would block.
function securityHeaders(env) {
  const clerkApi = clerkFrontendApi(env.VITE_CLERK_PUBLISHABLE_KEY)
  const apiOrigin = env.VITE_API_URL ? new URL(env.VITE_API_URL).origin : null
  const turnstile = 'https://challenges.cloudflare.com'

  const csp = [
    "default-src 'self'",
    `script-src 'self' ${clerkApi ?? ''} ${turnstile}`,
    // Clerk injects its component styles at runtime, and the SVG world uses
    // inline style attributes, so inline styles must stay allowed
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: https://img.clerk.com",
    "font-src 'self'",
    `connect-src 'self' ${clerkApi ?? ''} ${apiOrigin ?? ''}`,
    `frame-src ${turnstile}`,
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ]
    .map((directive) => directive.replace(/\s+/g, ' ').trim())
    .join('; ')

  return {
    'Content-Security-Policy': csp,
    'Strict-Transport-Security': 'max-age=31536000',
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Permissions-Policy': 'geolocation=(), microphone=(), camera=(), payment=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
  }
}

// Emits dist/.htaccess with the same headers for the Apache host
function htaccess(headers) {
  return {
    name: 'security-headers-htaccess',
    apply: 'build',
    generateBundle() {
      const lines = Object.entries(headers).map(
        ([name, value]) => `  Header always set ${name} "${value}"`
      )
      this.emitFile({
        type: 'asset',
        fileName: '.htaccess',
        source: [
          '# Generated by vite.config.js at build time. Do not edit by hand.',
          'Options -Indexes',
          'ServerSignature Off',
          '',
          '<IfModule mod_headers.c>',
          ...lines,
          '  Header always unset X-Powered-By',
          '</IfModule>',
          '',
        ].join('\n'),
      })
    },
  }
}

// https://vite.dev/config/
export default defineConfig(({ command, mode, isPreview }) => {
  const env = loadEnv(mode, process.cwd())
  const headers = securityHeaders(env)
  // Sub-path the production build is served from (e.g. /nimeoniter/),
  // read from .env. Must start and end with a slash.
  const basePath = env.VITE_BASE_PATH || '/'

  return {
    plugins: [react(), htaccess(headers)],
    // The dev server (npm run dev) stays at the root for local development
    // and tests; the build and its preview use the deployment sub-path.
    base: command === 'build' || isPreview ? basePath : '/',
    preview: { headers },
  }
})